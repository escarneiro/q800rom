def grid(s):
    return [list(line) for line in s.strip('\n').split('\n')]


def overlay(base, art, top, left):
    g = [r[:] for r in base]
    for dy, line in enumerate(art):
        for dx, c in enumerate(line):
            if c == '#':
                g[top + dy][left + dx] = '#'
    return g


def save(g, path):
    assert len(g) == 32 and all(len(r) == 32 for r in g), path
    im = Image.new('L', (32, 32), 255)
    for y, row in enumerate(g):
        for x, c in enumerate(row):
            if c == '#':
                im.putpixel((x, y), 0)
    im.save(path)


def main():
    chime(os.path.join(HERE, 'chime.wav'))
    out = os.path.join(HERE, 'booticons')
    os.makedirs(out, exist_ok=True)
    d = grid(disk)
    save(grid(happy), os.path.join(out, 'happy.png'))
    save(d, os.path.join(out, 'disk.png'))
    save(overlay(d, q, 15, 2), os.path.join(out, 'diskq.png'))
    save(overlay(d, x, 17, 2), os.path.join(out, 'diskx.png'))


