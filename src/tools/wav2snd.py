#!/usr/bin/env python3
"""wav2snd.py - turn a WAV file into an uncompressed Macintosh 'snd ' (format 1).

The sound is mixed to mono, resampled to 22254.545 Hz (the Mac's native rate) and
stored as 8-bit unsigned samples with a standard sound header (encode stdSH), which
BOOTBEEPPATCH plays on every sound chip.

Usage:
  wav2snd.py in.wav out.snd                 'snd ' resource data
  wav2snd.py in.wav out.bin --raw           sample bytes only
  wav2snd.py in.wav bootchime.s --asm SIZE  romsrc/sound/bootchime.s replacement:
                                            one sound for all three labels, padded to
                                            SIZE bytes (the size of the sound area) so
                                            nothing after it moves
  wav2snd.py in.wav alertsound.s --asm SIZE --label ALERTSOUND
                                            romsrc/sound/alertsound.s replacement (the
                                            alert sound, 'snd ' 1), SIZE bytes

Options: --gain G (default: normalize to full scale), --fade MS (fade-out applied
when the sound is cut to fit; default 50).
"""
import argparse
import struct
import sys
import wave

RATE_FIXED = 0x56EE8BA3                 # 22254.545 Hz as 16.16 fixed point
RATE = RATE_FIXED / 65536.0
SND_HEADER = 20                         # format 1 resource up to the sound header
STD_HEADER = 22                         # standard sound header before the samples


def read_wav(path):
    with wave.open(path, 'rb') as w:
        ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    vals = []
    step = width * ch
    for i in range(0, len(raw) - step + 1, step):
        s = 0.0
        for c in range(ch):
            b = raw[i + c * width:i + (c + 1) * width]
            if width == 1:
                v = (b[0] - 128) / 128.0
            else:
                v = int.from_bytes(b, 'little', signed=True) / float(1 << (8 * width - 1))
            s += v
        vals.append(s / ch)
    return vals, rate


def resample(vals, src, dst):
    if not vals:
        return []
    if src == dst:
        return list(vals)
    n = int(len(vals) * dst / src)
    out = []
    for i in range(n):
        x = i * src / dst
        j = int(x)
        f = x - j
        a = vals[j]
        b = vals[j + 1] if j + 1 < len(vals) else a
        out.append(a + (b - a) * f)
    return out


def to_u8(vals, gain, max_len, fade_ms):
    if max_len is not None and len(vals) > max_len:
        vals = vals[:max_len]
        nf = min(len(vals), int(RATE * fade_ms / 1000))
        for k in range(nf):
            vals[len(vals) - nf + k] *= 1.0 - (k + 1) / nf
    if gain is None:
        peak = max((abs(v) for v in vals), default=0.0)
        gain = 1.0 / peak if peak else 1.0
    out = bytearray()
    for v in vals:
        out.append(max(0, min(255, int(round(128 + v * gain * 127)))))
    # end at the centre value so the speaker doesn't click
    while out and out[-1] != 0x80 and abs(out[-1] - 0x80) < 3:
        out[-1] = 0x80
    return bytes(out)


def snd_resource(samples):
    hdr = struct.pack('>HHHIHHHI', 1, 1, 5, 0x80, 1, 0x8051, 0, SND_HEADER)
    std = struct.pack('>IIIIIBB', 0, len(samples), RATE_FIXED, 0, 0, 0, 60)
    return hdr + std + samples


def asm(samples, binname, size, label='BOOTCHIME'):
    pad = size - SND_HEADER - STD_HEADER - len(samples)
    if label == 'BOOTCHIME':
        head = ["| sound/bootchime.s - the boot chime, played by BOOTBEEPPATCH (patches/beeppatches.s)",
                "|",
                "| Generated by tools/wav2snd.py: one uncompressed 'snd ' format 1 sound (8-bit,",
                "| 22254.5 Hz) used for every sound chip. Samples in sound/%s." % binname,
                "",
                "BOOTCHIME_ALT:",
                "BOOTCHIME_PLAIN:"]
    else:
        head = ["| Generated by tools/wav2snd.py: one uncompressed 'snd ' format 1 sound (8-bit,",
                "| 22254.5 Hz). Samples in sound/%s." % binname,
                ""]
    lines = head + [
        "%(L)s:" % {"L": label},
        "    .short  1                  | format 1",
        "    .short  1                  | one synthesizer",
        "    .short  5                  | sampledSynth",
        "    .long   0x00000080         | init: initMono",
        "    .short  1                  | one command",
        "    .short  0x8051             | bufferCmd (data offset flag set)",
        "    .short  0                  | param1",
        "    .long   %(L)s_header-%(L)s  | param2: offset of the sound header",
        "%(L)s_header:",
        "    .long   0x00000000         | samplePtr (0: data follows)",
        "    .long   %(L)s_end-%(L)s_data  | length in bytes",
        "    .long   0x%08X         | sampleRate (Fixed, %.1f Hz)" % (RATE_FIXED, RATE),
        "    .long   0, 0               | loopStart, loopEnd",
        "    .byte   0x00, 60           | encode stdSH, baseFrequency",
        "%(L)s_data:",
        '    .incbin "sound/%s"' % binname,
        "%(L)s_end:",
    ]
    lines = [l.replace('%(L)s', label) for l in lines]
    if pad:
        lines.append("    .fill   %d, 1, 0           | padding up to the end of the sound area" % pad)
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('wav')
    ap.add_argument('out')
    g = ap.add_mutually_exclusive_group()
    g.add_argument('--raw', action='store_true', help='write the sample bytes only')
    g.add_argument('--asm', type=lambda s: int(s, 0), metavar='SIZE',
                   help='write a bootchime.s replacement padded to SIZE bytes (plus a .bin)')
    ap.add_argument('--label', default='BOOTCHIME', help='label of the sound with --asm (default BOOTCHIME)')
    ap.add_argument('--gain', type=float, help='gain (default: normalize)')
    ap.add_argument('--fade', type=float, default=50, help='fade-out in ms when cut (default 50)')
    a = ap.parse_args()

    vals, rate = read_wav(a.wav)
    vals = resample(vals, rate, RATE)
    max_len = a.asm - SND_HEADER - STD_HEADER if a.asm else None
    if max_len is not None and len(vals) > max_len:
        print('note: %.2f s cut to %.2f s to fit %d bytes' % (len(vals) / RATE, max_len / RATE, a.asm),
              file=sys.stderr)
    samples = to_u8(vals, a.gain, max_len, a.fade)

    if a.raw:
        open(a.out, 'wb').write(samples)
    elif a.asm:
        binpath = a.out[:-2] + '.bin' if a.out.endswith('.s') else a.out + '.bin'
        binname = binpath.replace('\\', '/').rsplit('/', 1)[-1]
        open(binpath, 'wb').write(samples)
        open(a.out, 'w').write(asm(samples, binname, a.asm, a.label))
        print('wrote %s and %s' % (a.out, binpath), file=sys.stderr)
    else:
        open(a.out, 'wb').write(snd_resource(samples))
    print('%d samples, %.2f s at %.1f Hz' % (len(samples), len(samples) / RATE, RATE), file=sys.stderr)


if __name__ == '__main__':
    main()
