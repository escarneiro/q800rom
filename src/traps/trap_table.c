const MacTrapEntry* LookupTrapByNum(uint16_t trap_num) {
    if (trap_num >= 0xA800 && trap_num < 0xAC00) {
        return &g_mac_toolbox_traps[trap_num & 0x03FF];
    } else if (trap_num >= 0xA000 && trap_num < 0xA800) {
        return &g_mac_os_traps[trap_num & 0x00FF];
    }
    return NULL;
}

const MacTrapEntry* LookupTrapByName(const char *name) {
    if (!name) return NULL;
    for (int i = 0; i < 256; i++) {
        if (strcmp(g_mac_os_traps[i].name, name) == 0) return &g_mac_os_traps[i];
    }
    for (int i = 0; i < 1024; i++) {
        if (strcmp(g_mac_toolbox_traps[i].name, name) == 0) return &g_mac_toolbox_traps[i];
    }
    return NULL;
}
